-- 006: 清理数据污染与脏编码。
--
-- 1) 早期的「基础信息」导入把批次名写进了 category（物料类别），
--    导致类别下拉里出现「旧版基础信息」这种不是类别的值。
-- 2) 台账里混进了只有 "-" / "0" 的脏编码，开单下拉会显示出来。

-- 类别清空（NULL 表示未分类，比塞一个假类别更诚实）
UPDATE items SET category = NULL WHERE category = '旧版基础信息';

-- 删除无意义的物料编码记录（"-" 与 "0" 是粘贴残留，不是真编码）
-- 只删主数据里的，台账历史行不动。
DELETE FROM items WHERE TRIM(item_code) IN ('-', '0') AND TRIM(COALESCE(item_name, '')) = '';

-- 名称与编码完全相同的占位记录：保留（有些确实是按名称建号的），
-- 但把编码前缀 "基础-" 的记录标成未分类以外的状态由用户决定，这里不动。
